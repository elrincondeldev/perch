import { afterEach, beforeEach, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { firstPrompt } from "./transcript.ts";

const ID = "0603472f-b7c5-4dae-b7a1-142468264b30";
let root: string;
beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "tomari-transcripts-"));
  mkdirSync(join(root, "-Users-dev-app"));
});
afterEach(() => rmSync(root, { recursive: true, force: true }));

const line = (entry: object) => JSON.stringify(entry);
const user = (content: unknown, extra: object = {}) => line({ type: "user", message: { role: "user", content }, ...extra });
const write = (lines: string[], name = `${ID}.jsonl`) => {
  const path = join(root, "-Users-dev-app", name);
  writeFileSync(path, lines.join("\n") + "\n");
  return path;
};

test("the first real prompt is read, skipping meta, wrapped, empty and tool-result entries", async () => {
  write([
    line({ type: "summary", summary: "x" }),
    user("Caveat: the messages below were generated by the user", { isMeta: true }),
    user("<command-name>/clear</command-name>"),
    user("<local-command-stdout></local-command-stdout>"),
    user("<system-reminder>be nice</system-reminder>"),
    user("   "),
    user([{ type: "tool_result", tool_use_id: "t1", content: "ok" }]),
    "not json at all",
    user([{ type: "text", text: "fix the login redirect" }]),
    user("a later prompt"),
  ]);
  expect(await firstPrompt(ID, { root })).toBe("fix the login redirect");
});

test("a plain string prompt works, and the path from the hook is preferred", async () => {
  const path = write([user("hello there")], "other-name.jsonl");
  expect(await firstPrompt(ID, { root, transcriptPath: path })).toBe("hello there");
});

test("it returns null when there is no transcript or no real prompt", async () => {
  expect(await firstPrompt(ID, { root })).toBeNull();
  write([user("<command-name>/clear</command-name>")]);
  expect(await firstPrompt(ID, { root })).toBeNull();
});

test("a transcript_path outside the projects folder is never read", async () => {
  const outside = mkdtempSync(join(tmpdir(), "tomari-outside-"));
  try {
    const path = join(outside, "secret.jsonl");
    writeFileSync(path, user("leaked") + "\n");
    expect(await firstPrompt(ID, { root, transcriptPath: path })).toBeNull();
    expect(await firstPrompt(ID, { root, transcriptPath: join(root, "..", "x", "secret.jsonl") })).toBeNull();
    expect(await firstPrompt(ID, { root, transcriptPath: "relative/x.jsonl" })).toBeNull();
  } finally {
    rmSync(outside, { recursive: true, force: true });
  }
});

test("only a bounded head is read, and a cut last line is ignored", async () => {
  write([user("x".repeat(300)), user("beyond the head")]);
  expect(await firstPrompt(ID, { root, headBytes: 100 })).toBeNull();
  expect(await firstPrompt(ID, { root, headBytes: 10_000 })).toBe("x".repeat(300));
});

test("a session id that is not a plain id never reaches the file system", async () => {
  expect(await firstPrompt("../../etc/passwd", { root })).toBeNull();
});
